#!/usr/bin/env node
/**
 * Regenerates src/certificates/assets.generated.ts from the binary files in
 * src/certificates/assets/.
 *
 * The certificate fonts and logo are inlined as base64 so they are always
 * bundled into the Vercel serverless function. Reading them from disk at
 * runtime depends on Next's output file tracing and can silently break.
 *
 * Run after replacing a font or the logo:
 *   node scripts/embed-certificate-assets.js
 */
const fs = require('fs');
const path = require('path');

const ASSET_DIR = path.join(__dirname, '..', 'src', 'certificates', 'assets');
const OUT_FILE = path.join(__dirname, '..', 'src', 'certificates', 'assets.generated.ts');

const ASSETS = {
  ARMENIAN_REGULAR_TTF: 'NotoSerifArmenian-Regular.ttf',
  ARMENIAN_BOLD_TTF: 'NotoSerifArmenian-Bold.ttf',
  DIOCESE_LOGO_JPEG: 'western_diocese_logo.jpeg',
};

let out =
  '// AUTO-GENERATED by scripts/embed-certificate-assets.js. Do not edit by hand.\n' +
  '// Fonts: Noto Serif Armenian (SIL Open Font License 1.1, see assets/OFL.txt),\n' +
  '// static Regular/Bold instances of the Google Fonts variable build.\n\n';

for (const [name, file] of Object.entries(ASSETS)) {
  const b64 = fs.readFileSync(path.join(ASSET_DIR, file)).toString('base64');
  out += `export const ${name} =\n  '${b64}';\n\n`;
}

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)} (${Math.round(out.length / 1024)} KB)`);
